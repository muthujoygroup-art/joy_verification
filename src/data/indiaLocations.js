export const getDistrictsByState = (stateName) => {
  if (!stateName) return ['Other District'];
  
  if (INDIA_STATES_AND_DISTRICTS[stateName]) {
    return INDIA_STATES_AND_DISTRICTS[stateName];
  }

  // Alias / Fuzzy matching for common state naming conventions
  const normalized = String(stateName).toLowerCase().trim();
  if (normalized.includes('delhi')) {
    return INDIA_STATES_AND_DISTRICTS["Delhi (National Capital Territory)"] || ['Other District'];
  }
  if (normalized.includes('tamil') || normalized === 'tn') {
    return INDIA_STATES_AND_DISTRICTS["Tamil Nadu"] || ['Other District'];
  }
  if (normalized.includes('karnataka') || normalized === 'ka') {
    return INDIA_STATES_AND_DISTRICTS["Karnataka"] || ['Other District'];
  }
  if (normalized.includes('maharashtra') || normalized === 'mh') {
    return INDIA_STATES_AND_DISTRICTS["Maharashtra"] || ['Other District'];
  }
  if (normalized.includes('andhra') || normalized === 'ap') {
    return INDIA_STATES_AND_DISTRICTS["Andhra Pradesh"] || ['Other District'];
  }
  if (normalized.includes('telangana') || normalized === 'ts' || normalized === 'tg') {
    return INDIA_STATES_AND_DISTRICTS["Telangana"] || ['Other District'];
  }
  if (normalized.includes('kerala') || normalized === 'kl') {
    return INDIA_STATES_AND_DISTRICTS["Kerala"] || ['Other District'];
  }
  if (normalized.includes('uttar pradesh') || normalized === 'up') {
    return INDIA_STATES_AND_DISTRICTS["Uttar Pradesh"] || ['Other District'];
  }

  const matchedKey = Object.keys(INDIA_STATES_AND_DISTRICTS).find(k => k.toLowerCase() === normalized);
  if (matchedKey) {
    return INDIA_STATES_AND_DISTRICTS[matchedKey];
  }

  return ['Other District'];
};

/**
 * Check if a location value represents a custom / other selection
 * @param {string} val
 * @returns {boolean}
 */
export const isOtherLocation = (val) => {
  if (!val) return false;
  const s = String(val).toLowerCase().trim();
  return (
    s === 'others' || 
    s === 'other' || 
    s.startsWith('other ') || 
    s === 'other state / union territory' || 
    s === 'other district'
  );
};
